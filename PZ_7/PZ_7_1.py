# Дана строка. Если она представляет собой запись целого числа, то вывести 1,
# если вещественного (с дробной частью) — вывести 2; если строку нельзя
# преобразовать в число, то вывести 0. Дробная часть отделяется точкой «.»

S = input('Введите строку: ')
k = 0 
if S != '':
    T = S
    if T[0] == '+' or T[0] == '-':
        T = T[1:]

    if T != '':
        if T.find('.') == -1:
            if T.isdigit():
                k = 1
        else:
            if T.count('.') == 1:
                Cel, Drob = T.split('.')
                if Cel != '' and Drob != '':
                    if Cel.isdigit() and Drob.isdigit():
                        k = 2
print('Результат:', k)
